import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayNotEmpty,
  IsArray,
  IsEmail,
  IsIn,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Length,
  Matches,
  MaxLength,
  ValidateNested,
} from 'class-validator';
import { ACCESS_REQUEST_STATUSES, type AccessRequestStatus } from '../../common/constants';
import { PaginationQueryDto } from '../../common/pagination.dto';
import { RoleAssignmentDto } from '../../users/dto/user.dto';

const DEVICE_SECRET_PATTERN = /^[A-Za-z0-9_-]+$/;

export class DeviceCredentialDto {
  @ApiProperty({
    description: 'Random secret generated by the browser (base64url, 43 to 128 characters)',
  })
  @IsString()
  @Length(43, 128)
  @Matches(DEVICE_SECRET_PATTERN)
  deviceSecret!: string;
}

export class CreateAccessRequestDto extends DeviceCredentialDto {
  @ApiProperty({ example: 'nombre@tcs.com' })
  @IsEmail()
  @MaxLength(320)
  email!: string;

  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  fullName!: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(120)
  department?: string;

  @ApiPropertyOptional({ description: 'Browser and system, shown to the SUPERADMIN' })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceLabel?: string;
}

export class AccessRequestStatusQueryDto extends DeviceCredentialDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  requestId!: string;
}

export class ListAccessRequestsQueryDto extends PaginationQueryDto {
  @ApiPropertyOptional({ enum: ACCESS_REQUEST_STATUSES, enumName: 'AccessRequestStatus' })
  @IsOptional()
  @IsIn(ACCESS_REQUEST_STATUSES)
  status?: AccessRequestStatus;
}

export class ApproveAccessRequestDto {
  @ApiPropertyOptional({
    description: 'Roles of a new user (defaults to ASOCIADO). Not allowed for an existing user',
    type: [RoleAssignmentDto],
  })
  @IsOptional()
  @IsArray()
  @ArrayNotEmpty()
  @ValidateNested({ each: true })
  @Type(() => RoleAssignmentDto)
  roles?: RoleAssignmentDto[];
}

export class RejectAccessRequestDto {
  @ApiProperty({ description: 'Reason shown to the person who asked for access' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(500)
  comment!: string;
}
